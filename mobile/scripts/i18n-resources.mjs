#!/usr/bin/env node
// Writes src/i18n/resources.ts: one static import per locales/<lang>/<area>.json (Metro needs
// static imports), merged per language. Run after adding a language or an area file.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dir = join(root, 'src/i18n/locales');
const langs = readdirSync(dir).filter((n) => statSync(join(dir, n)).isDirectory()).sort((a, b) => (a === 'en' ? -1 : b === 'en' ? 1 : a.localeCompare(b)));
const imports = [];
const entries = [];
for (const lang of langs) {
  const areas = readdirSync(join(dir, lang)).filter((n) => n.endsWith('.json')).map((n) => n.replace(/\.json$/, '')).sort();
  const names = areas.map((area) => {
    const name = `${lang}_${area}`;
    imports.push(`import ${name} from './locales/${lang}/${area}.json';`);
    return name;
  });
  entries.push(`  ${lang}: { translation: { ${names.map((n) => `...${n}`).join(', ')} } },`);
}
writeFileSync(
  join(root, 'src/i18n/resources.ts'),
  `// Generated by scripts/i18n-resources.mjs from locales/<lang>/*.json — do not edit by hand.\n${imports.join('\n')}\n\nexport const resources = {\n${entries.join('\n')}\n};\n`,
);
console.log(`resources.ts: ${langs.join(', ')}`);
